-- =====================================================================
-- V4 - Atividades físicas, histórico de peso e consumo de água.
-- =====================================================================

CREATE TABLE atividades (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id            BIGINT       NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    treino_id             BIGINT       REFERENCES treinos (id) ON DELETE SET NULL,
    nome                  VARCHAR(120) NOT NULL,
    data_atividade        DATE         NOT NULL,
    horario               TIME         NOT NULL,
    duracao_min           INTEGER      NOT NULL CHECK (duracao_min BETWEEN 1 AND 1440),
    calorias_gastas       INTEGER      NOT NULL CHECK (calorias_gastas >= 0),
    exercicios_concluidos INTEGER      NOT NULL CHECK (exercicios_concluidos >= 0),
    exercicios_total      INTEGER      NOT NULL CHECK (exercicios_total >= 0),
    criado_em             TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_atividades_usuario_data ON atividades (usuario_id, data_atividade);

CREATE TABLE registros_peso (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT       NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    data        DATE         NOT NULL,
    peso_kg     NUMERIC(5,1) NOT NULL CHECK (peso_kg > 0 AND peso_kg <= 500),
    criado_em   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_registros_peso_usuario_data UNIQUE (usuario_id, data)
);

CREATE TABLE registros_agua (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT      NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    data          DATE        NOT NULL,
    quantidade_ml INTEGER     NOT NULL CHECK (quantidade_ml BETWEEN 1 AND 5000),
    criado_em     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_registros_agua_usuario_data ON registros_agua (usuario_id, data);
