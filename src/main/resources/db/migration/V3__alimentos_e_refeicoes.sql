-- =====================================================================
-- V3 - Catálogo de alimentos (dados de referência) e refeições.
-- =====================================================================

CREATE TABLE alimentos (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              VARCHAR(120)  NOT NULL UNIQUE,
    porcao_quantidade NUMERIC(8,2)  NOT NULL CHECK (porcao_quantidade > 0),
    porcao_unidade    VARCHAR(10)   NOT NULL CHECK (porcao_unidade IN ('g', 'ml', 'unidade')),
    calorias          NUMERIC(8,1)  NOT NULL CHECK (calorias >= 0),
    proteinas         NUMERIC(8,1)  NOT NULL CHECK (proteinas >= 0),
    carboidratos      NUMERIC(8,1)  NOT NULL CHECK (carboidratos >= 0),
    gorduras          NUMERIC(8,1)  NOT NULL CHECK (gorduras >= 0)
);

CREATE TABLE refeicoes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT      NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    nome           VARCHAR(40) NOT NULL,
    data_refeicao  DATE        NOT NULL,
    horario        TIME        NOT NULL,
    criado_em      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_refeicoes_usuario_data ON refeicoes (usuario_id, data_refeicao);

CREATE TABLE refeicao_itens (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refeicao_id    BIGINT        NOT NULL REFERENCES refeicoes (id) ON DELETE CASCADE,
    -- O alimento pode sair do catálogo; o nome e os valores ficam gravados no item.
    alimento_id    BIGINT        REFERENCES alimentos (id) ON DELETE SET NULL,
    nome_alimento  VARCHAR(120)  NOT NULL,
    quantidade     NUMERIC(8,2)  NOT NULL CHECK (quantidade > 0),
    unidade        VARCHAR(10)   NOT NULL,
    calorias       INTEGER       NOT NULL CHECK (calorias >= 0),
    proteinas      NUMERIC(8,1)  NOT NULL CHECK (proteinas >= 0),
    carboidratos   NUMERIC(8,1)  NOT NULL CHECK (carboidratos >= 0),
    gorduras       NUMERIC(8,1)  NOT NULL CHECK (gorduras >= 0)
);
CREATE INDEX idx_refeicao_itens_refeicao ON refeicao_itens (refeicao_id);

