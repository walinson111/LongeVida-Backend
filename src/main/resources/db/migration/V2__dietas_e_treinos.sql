-- =====================================================================
-- V2 - Dietas, treinos e exercícios (com publicação e importação).
-- =====================================================================

CREATE TABLE dietas (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       BIGINT        NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    nome             VARCHAR(120)  NOT NULL,
    descricao        VARCHAR(500),
    calorias         INTEGER       NOT NULL CHECK (calorias BETWEEN 0 AND 10000),
    proteinas        NUMERIC(6,1)  NOT NULL DEFAULT 0 CHECK (proteinas BETWEEN 0 AND 1000),
    carboidratos     NUMERIC(6,1)  NOT NULL DEFAULT 0 CHECK (carboidratos BETWEEN 0 AND 1000),
    gorduras         NUMERIC(6,1)  NOT NULL DEFAULT 0 CHECK (gorduras BETWEEN 0 AND 1000),
    status           VARCHAR(10)   NOT NULL DEFAULT 'PRIVADA' CHECK (status IN ('PRIVADA', 'PUBLICA')),
    -- Importação: guarda a origem e o nome de quem publicou (crédito),
    -- mesmo que o original seja apagado depois.
    origem_dieta_id  BIGINT        REFERENCES dietas (id) ON DELETE SET NULL,
    credito_nome     VARCHAR(120),
    criado_em        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    atualizado_em    TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_dietas_usuario ON dietas (usuario_id);
CREATE INDEX idx_dietas_publicas ON dietas (usuario_id) WHERE status = 'PUBLICA';

CREATE TABLE treinos (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id        BIGINT       NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    nome              VARCHAR(120) NOT NULL,
    objetivo          VARCHAR(120) NOT NULL,
    nivel             VARCHAR(20)  NOT NULL CHECK (nivel IN ('INICIANTE', 'INTERMEDIARIO', 'AVANCADO')),
    status            VARCHAR(10)  NOT NULL DEFAULT 'PRIVADA' CHECK (status IN ('PRIVADA', 'PUBLICA')),
    origem_treino_id  BIGINT       REFERENCES treinos (id) ON DELETE SET NULL,
    credito_nome      VARCHAR(120),
    criado_em         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em     TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_treinos_usuario ON treinos (usuario_id);
CREATE INDEX idx_treinos_publicos ON treinos (usuario_id) WHERE status = 'PUBLICA';

CREATE TABLE exercicios (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    treino_id      BIGINT       NOT NULL REFERENCES treinos (id) ON DELETE CASCADE,
    ordem          INTEGER      NOT NULL,
    nome           VARCHAR(120) NOT NULL,
    series         INTEGER      NOT NULL CHECK (series BETWEEN 1 AND 99),
    repeticoes     INTEGER      NOT NULL CHECK (repeticoes BETWEEN 1 AND 999),
    grupo_muscular VARCHAR(60)  NOT NULL DEFAULT ''
);
CREATE INDEX idx_exercicios_treino ON exercicios (treino_id, ordem);
