-- =====================================================================
-- V1 - Usuários, configurações/metas, restrições alimentares,
--      perfis profissionais, seguidores e recuperação de senha.
-- =====================================================================

CREATE TABLE usuarios (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             VARCHAR(120) NOT NULL,
    email            VARCHAR(160) NOT NULL,
    senha_hash       VARCHAR(100) NOT NULL,
    idade            INTEGER      NOT NULL CHECK (idade BETWEEN 1 AND 120),
    peso_kg          NUMERIC(5,1) CHECK (peso_kg > 0 AND peso_kg <= 500),
    altura_cm        INTEGER      CHECK (altura_cm BETWEEN 50 AND 250),
    nivel_atividade  VARCHAR(20)  CHECK (nivel_atividade IN ('SEDENTARIO', 'LEVE', 'MODERADO', 'INTENSO')),
    foto_url         VARCHAR(500),
    -- Incrementado ao redefinir a senha: invalida todos os JWT emitidos antes.
    token_version    INTEGER      NOT NULL DEFAULT 0,
    ativo            BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- E-mail único, sem diferenciar maiúsculas/minúsculas.
CREATE UNIQUE INDEX uk_usuarios_email ON usuarios (lower(email));

CREATE TABLE usuario_restricoes (
    usuario_id  BIGINT      NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    restricao   VARCHAR(20) NOT NULL CHECK (restricao IN ('DIABETES', 'HIPERTENSAO', 'LACTOSE', 'GLUTEN', 'OUTRAS')),
    PRIMARY KEY (usuario_id, restricao)
);

CREATE TABLE configuracoes_usuario (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id            BIGINT  NOT NULL UNIQUE REFERENCES usuarios (id) ON DELETE CASCADE,
    notificacoes_ativas   BOOLEAN NOT NULL DEFAULT TRUE,
    meta_agua_ml          INTEGER NOT NULL DEFAULT 2000 CHECK (meta_agua_ml BETWEEN 1 AND 10000),
    meta_calorias         INTEGER NOT NULL DEFAULT 2000 CHECK (meta_calorias BETWEEN 1 AND 10000),
    meta_exercicio_min    INTEGER NOT NULL DEFAULT 30   CHECK (meta_exercicio_min BETWEEN 1 AND 1440),
    meta_calorias_gastas  INTEGER NOT NULL DEFAULT 500  CHECK (meta_calorias_gastas BETWEEN 1 AND 10000)
);

CREATE TABLE perfis_profissionais (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id             BIGINT       NOT NULL UNIQUE REFERENCES usuarios (id) ON DELETE CASCADE,
    especialidade          VARCHAR(60)  NOT NULL,
    registro_profissional  VARCHAR(30)  NOT NULL,
    descricao              VARCHAR(500),
    criado_em              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em          TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE seguidores (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seguidor_id      BIGINT      NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    profissional_id  BIGINT      NOT NULL REFERENCES perfis_profissionais (id) ON DELETE CASCADE,
    criado_em        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_seguidores UNIQUE (seguidor_id, profissional_id)
);
CREATE INDEX idx_seguidores_profissional ON seguidores (profissional_id);

CREATE TABLE password_reset_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT       NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    codigo_hash VARCHAR(100) NOT NULL,
    expira_em   TIMESTAMPTZ  NOT NULL,
    tentativas  INTEGER      NOT NULL DEFAULT 0,
    usado_em    TIMESTAMPTZ,
    criado_em   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_password_reset_usuario ON password_reset_tokens (usuario_id);
