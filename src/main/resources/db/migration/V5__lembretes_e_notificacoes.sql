-- =====================================================================
-- V5 - Lembretes diários e notificações dentro do app.
-- =====================================================================

CREATE TABLE lembretes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT      NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    tipo        VARCHAR(20) NOT NULL CHECK (tipo IN ('REFEICAO', 'TREINO', 'AGUA')),
    titulo      VARCHAR(80) NOT NULL,
    horario     TIME        NOT NULL,
    ativo       BOOLEAN     NOT NULL DEFAULT TRUE,
    criado_em   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_lembretes_usuario ON lembretes (usuario_id);
CREATE INDEX idx_lembretes_horario ON lembretes (horario) WHERE ativo;

CREATE TABLE notificacoes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      BIGINT       NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    tipo            VARCHAR(20)  NOT NULL CHECK (tipo IN ('LEMBRETE', 'TREINO', 'SOCIAL')),
    titulo          VARCHAR(120) NOT NULL,
    mensagem        VARCHAR(300) NOT NULL,
    lida            BOOLEAN      NOT NULL DEFAULT FALSE,
    lembrete_id     BIGINT       REFERENCES lembretes (id) ON DELETE CASCADE,
    referencia_data DATE,
    criada_em       TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_notificacoes_usuario ON notificacoes (usuario_id, criada_em DESC);
-- Garante no máximo uma notificação por lembrete por dia.
CREATE UNIQUE INDEX uk_notificacoes_lembrete_dia ON notificacoes (lembrete_id, referencia_data)
    WHERE lembrete_id IS NOT NULL;
