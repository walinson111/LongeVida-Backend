-- =====================================================================
-- V6 - Estrutura para dispositivos vestíveis (wearables).
-- O backend só guarda e consulta os dados; a leitura do relógio/pulseira
-- (HealthKit, Health Connect, API do fabricante) é feita no app e enviada
-- para o endpoint de medições.
-- =====================================================================

CREATE TABLE dispositivos (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id            BIGINT       NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    nome                  VARCHAR(80)  NOT NULL,
    marca                 VARCHAR(40)  NOT NULL,
    identificador_externo VARCHAR(120),
    conectado             BOOLEAN      NOT NULL DEFAULT TRUE,
    ultima_sincronizacao  TIMESTAMPTZ,
    criado_em             TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_dispositivos_usuario ON dispositivos (usuario_id);

CREATE TABLE medicoes_wearable (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispositivo_id  BIGINT        NOT NULL REFERENCES dispositivos (id) ON DELETE CASCADE,
    usuario_id      BIGINT        NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    tipo            VARCHAR(30)   NOT NULL CHECK (tipo IN ('PASSOS', 'FREQUENCIA_CARDIACA', 'CALORIAS_GASTAS', 'SONO_MINUTOS')),
    valor           NUMERIC(10,2) NOT NULL CHECK (valor >= 0),
    medido_em       TIMESTAMPTZ   NOT NULL,
    criado_em       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uk_medicao_dispositivo_tipo_instante UNIQUE (dispositivo_id, tipo, medido_em)
);
CREATE INDEX idx_medicoes_usuario_tipo ON medicoes_wearable (usuario_id, tipo, medido_em DESC);
